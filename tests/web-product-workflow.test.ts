  const retest = await running(recheck.target_task_id);
  assert.equal(retest.threadId, tester.threadId);
  writeFileSync(join(f.root, paths[2]), reportText);
  const issue = (await f.invoke('design-test', 'get_project_item', { id: issueId }, 'definition-issue')).item;
  await f.invoke('design-test', 'update_project_item', { request_id: 'definition-defect-closed', operation: 'edit', id: issueId, expected_revision: issue.revision, status: 'closed', reason: 'Static UI v2 recheck confirms retained input and retry; interactive behavior remains unverified.' }, 'definition-defect-closed');
