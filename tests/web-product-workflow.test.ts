import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { WorkflowEngine } from '../src/core/engine.js';
import { resolveMessageArtifact } from '../src/core/message-files.js';
import { insideProject } from '../src/core/paths.js';
import type { MessageReceipt, SendMessageInput } from '../src/shared/types.js';
import { collaborationFixture } from './collaboration-fixture.js';
import { until } from './runtime-fixture.js';

test('six Web roles compose HTTP collaboration, original Threads, control, versioned feedback and PM acceptance', async t => {
  const f = await collaborationFixture(t, 'web-product');
  assert.deepEqual(f.state.reviewPolicy.checkpoints.map(point => point.id), ['product-direction', 'ui-ue']);
  // This case isolates legacy collaboration/control; the default gated flow is tested separately.
  const configured = await f.engine.command({ type: 'save_review_policy', projectId: f.projectId, policy: { revision: f.state.reviewPolicy.revision, checkpoints: [] } });
  assert.deepEqual(configured.snapshot.selected!.reviewPolicy, { revision: 2, checkpoints: [] });
  const roles = ['product', 'requirements', 'design', 'frontend', 'backend', 'test'];
  const context = await f.invoke('product', 'get_project_context', {}, 'initial-context');
  assert.equal(context.project.template, 'web-product');
  assert.deepEqual(context.nodes.map((node: { id: string }) => node.id), roles);
  for (const node of context.nodes) {
    assert.ok(node.instructions.length > 0);
    assert.equal(node.planId, 'mvp-001');
  }
  assert.match(context.nodes[0].instructions, /产品经理维护/);
  assert.ok(context.edges.some((edge: { sourceNodeId: string; targetNodeId: string }) => edge.sourceNodeId === 'test' && edge.targetNodeId === 'frontend'));
  const running = async (receipt: MessageReceipt) => {
    await until(() => f.state.tasks.some(task => task.id === receipt.target_task_id && task.status === 'running' && !!task.turnId));
    return f.state.tasks.find(task => task.id === receipt.target_task_id)!;
  };
  const send = (from: string, to: string, request_id: string, content: unknown, extra: Partial<SendMessageInput> = {}) =>
    f.invoke(from, 'send_message', { request_id, to_node_id: to, content, reason: request_id, ...extra }, request_id) as Promise<MessageReceipt>;
  const userInput = [{ type: 'text', text: '  提交一条留言并显示服务端返回结果\n', text_elements: [], custom: { optional: null, flags: [false, 0, ''] } }];
  await f.engine.command({ type: 'send_message', projectId: f.projectId, nodeId: 'product', mode: 'codex', input: userInput });
  await until(() => f.state.tasks.some(task => task.nodeId === 'product' && !!task.turnId));
  const product = f.state.tasks[0];
  assert.deepEqual(f.state.conversation.find(entry => entry.taskId === product.id && entry.direction === 'input')!.content, userInput);
  await f.engine.command({ type: 'pause', projectId: f.projectId });
  f.finish(product, 'interrupted');
  await f.engine.command({ type: 'resume', projectId: f.projectId });
  await until(() => product.status === 'running' && !!product.turnId);
  assert.equal(f.state.tasks.length, 1, 'bulk resume only continues the interrupted PM task');
  assert.equal(f.state.nodes.find(node => node.id === 'requirements')!.status, 'idle');
  const productEdge = context.edges.find((edge: { id: string }) => edge.id === 'product-requirements');
  const brief = await send('product', 'requirements', 'brief', { flow: userInput[0].text, acceptance: ['display server result'], values: [null, false, 0, ''] }, { route: { edge_id: productEdge.id, edge_revision: productEdge.revision } });
  const requirements = await running(brief);
  assert.equal(product.status, 'running', 'HTTP acceptance must not end the sender Turn');
  assert.equal(product.terminal, null);
  assert.deepEqual(f.state.messages.find(message => message.message_id === brief.message_id)!.edgeSnapshot, productEdge);
  f.finish(product);

  const requirementsText = 'REQ-1 v1: submit text; show the exact server response, including whitespace.\n';
  const requirementsPath = insideProject(f.root, join(f.root, 'docs', 'design', 'requirements.md'));
  writeFileSync(requirementsPath, requirementsText);
  const designRequest = await send('requirements', 'design', 'design-request', { requirement: 'REQ-1', revision: 'requirements-v1' }, { attachments: [{ path: 'docs/design/requirements.md' }] });
  const backendRequest = await send('requirements', 'backend', 'backend-request', { requirement: 'REQ-1', contract: 'POST /messages returns {text}' });
  const testBaseline = await send('requirements', 'test', 'test-baseline', ['REQ-1', null, false, 0, '']);
  const design = await running(designRequest), backend = await running(backendRequest), baseline = await running(testBaseline);
  assert.equal(requirements.status, 'running', 'requirements can fan out before ending their own Turn');
  f.finish(requirements);
  const designContext = await f.invoke('design', 'get_project_context', {}, 'design-context');
  assert.equal(designContext.incoming_message.message_id, designRequest.message_id);
  assert.equal(designContext.incoming_message.from.nodeId, 'requirements');
  assert.deepEqual(designContext.task.input, { requirement: 'REQ-1', revision: 'requirements-v1' });
  const requirementArtifact = designContext.incoming_message.attachments[0];
  assert.equal(requirementArtifact.sha256, createHash('sha256').update(requirementsText).digest('hex'));
  writeFileSync(requirementsPath, 'REQ-1 v2: later author edit must not rewrite the accepted v1 attachment.\n');
  assert.equal(readFileSync(resolveMessageArtifact(f.root, f.state, requirementArtifact.artifact_id), 'utf8'), requirementsText);
  const designReady = await send('design', 'frontend', 'design-ready', { ui: 'input, submit, server result, error state', requirement: 'requirements-v1' }, { attachments: [{ artifact_id: requirementArtifact.artifact_id }] });
  const frontend = await running(designReady);
  f.finish(design);
  const contractReady = await send('backend', 'frontend', 'contract-ready', { contract: 'POST /messages', revision: 'api-v1', response: { text: ' original text ' } });
  const contractTask = f.state.tasks.find(task => task.id === contractReady.target_task_id)!;
  assert.equal(contractTask.status, 'queued', 'busy frontend retains the next contributor input');
  assert.equal(contractTask.turnId, null);
  assert.equal(frontend.status, 'running');
  f.finish(backend); f.finish(baseline); f.finish(frontend);
  await running(contractReady);
  assert.equal(contractTask.threadId, frontend.threadId, 'the second contributor continues the same frontend Thread');

  // This link has no suggested edge; architecture clarification still uses ordinary direct messaging.
  assert.equal(f.state.edges.some(edge => edge.sourceNodeId === 'frontend' && edge.targetNodeId === 'requirements'), false);
  const clarify = await send('frontend', 'requirements', 'clarify-whitespace', 'REQ-1: preserve whitespace?');
  const clarification = await running(clarify);
  const answer = await send('requirements', 'frontend', 'whitespace-answer', { preserveWhitespace: true }, { reply_to: clarify.message_id });
  const answerTask = f.state.tasks.find(task => task.id === answer.target_task_id)!;
  assert.equal(answerTask.status, 'queued');
  assert.equal(clarification.threadId, requirements.threadId);
  f.finish(clarification); f.finish(contractTask);
  const frontendAnswer = await running(answer);
  assert.equal(frontendAnswer.threadId, frontend.threadId);
  const originalTurn = frontendAnswer.turnId;
  await f.engine.command({ type: 'pause', projectId: f.projectId });
  f.finish(frontendAnswer, 'interrupted');
  assert.equal(frontendAnswer.status, 'paused');
  await f.engine.command({ type: 'resume_node', projectId: f.projectId, nodeId: 'frontend' });
  await until(() => frontendAnswer.status === 'running' && !!frontendAnswer.turnId && frontendAnswer.turnId !== originalTurn);
  assert.equal(frontendAnswer.threadId, frontend.threadId);
  assert.equal(f.state.nodes.find(node => node.id === 'test')!.status, 'paused', 'individual resume overrides bulk pause only for its node');
  const release = await send('frontend', 'test', 'release-v1', { sourceVersion: 'controlled-source-v1', requirement: 'requirements-v1', apiVersion: 'api-v1' }, { attachments: [{ artifact_id: requirementArtifact.artifact_id }] });
  assert.equal(f.state.tasks.find(task => task.id === release.target_task_id)!.status, 'queued');
  assert.equal(f.state.tasks.find(task => task.id === release.target_task_id)!.turnId, null);
  f.finish(frontendAnswer);
  await f.engine.command({ type: 'resume_node', projectId: f.projectId, nodeId: 'test' });
  const qa = await running(release);
  assert.equal(qa.threadId, baseline.threadId);
  const defectContent = { requirement: 'REQ-1', sourceVersion: 'controlled-source-v1', reproduce: ['submit "  hello  "'], expected: '  hello  ', actual: 'hello', owner: 'frontend' };
  const defect = await send('test', 'frontend', 'whitespace-defect', defectContent, { reply_to: release.message_id });
  const fix = await running(defect);
  assert.equal(fix.threadId, frontend.threadId);
  assert.deepEqual(fix.input, defectContent);
  assert.equal(f.state.messages.find(message => message.message_id === defect.message_id)!.toNodeId, 'frontend');
  f.finish(qa);
  const fixed = await send('frontend', 'test', 'release-v2', { sourceVersion: 'controlled-source-v2', corrected: 'preserve server response verbatim' }, { reply_to: defect.message_id });
  const retest = await running(fixed);
  f.finish(fix);
  const qaOutput = { id: 'qa-raw-result', type: 'agentMessage', text: 'REQ-1 passed on controlled-source-v2\n  whitespace preserved  ', evidence: { sourceVersion: 'controlled-source-v2', arbitrary: [null, false, 0, ''] } };
  const beforeOutput = f.state.messages.length;
  f.clients[0].options.onEvent({ method: 'item/completed', params: { threadId: retest.threadId, turnId: retest.turnId, item: qaOutput } });
  assert.equal(f.state.messages.length, beforeOutput, 'ordinary QA output does not become an automatic reply');
  const rawOutput = f.state.conversation.find(entry => entry.itemId === qaOutput.id)!;
  assert.deepEqual(rawOutput.rawItem, qaOutput); assert.deepEqual(rawOutput.content, qaOutput);
  assert.equal(rawOutput.text, qaOutput.text);
  const countBeforeResume = f.state.tasks.length;
  await f.engine.command({ type: 'resume', projectId: f.projectId });
  assert.equal(f.state.tasks.length, countBeforeResume, 'bulk resume does not manufacture tasks for idle roles');
  assert.equal(f.state.nodes.find(node => node.id === 'product')!.status, 'completed');
  const finalReport = { requirement: 'REQ-1', sourceVersion: 'controlled-source-v2', requirementSha256: requirementArtifact.sha256, results: [{ step: 'submit and display', status: 'passed' }], unverified: ['real model and browser execution'] };
  const report = await send('test', 'product', 'qa-acceptance', finalReport, { attachments: [{ artifact_id: requirementArtifact.artifact_id }] });
  f.finish(retest);
  const acceptance = await running(report);
  const countAtAcceptance = f.state.tasks.length;
  assert.equal(acceptance.threadId, product.threadId);
  const delivery = await f.invoke('test', 'get_delivery', { message_id: release.message_id }, 'release-delivery');
  assert.equal(delivery.attempts[0].status, 'completed');
  assert.equal(delivery.replies[0].message_id, defect.message_id);
  const feedbackHistory = await f.invoke('product', 'read_history', { reply_to: defect.message_id }, 'feedback-history');
  assert.ok(feedbackHistory.entries.some((entry: { messageId: string }) => entry.messageId === fixed.message_id));
  const acceptanceResult = { accepted: true, basedOnMessage: report.message_id, scope: ['REQ-1'], evidence: finalReport, optional: null };
  await f.invoke('product', 'complete_task', { result: acceptanceResult }, 'pm-complete');
  f.finish(acceptance);
  assert.deepEqual(acceptance.result, acceptanceResult);
  assert.equal(f.state.project.status, 'completed');
  assert.equal(f.state.tasks.length, countAtAcceptance, 'PM acceptance does not force another review or acknowledgment');
  assert.equal(f.state.handoffs.length, 0);
  assert.ok(f.state.tasks.every(task => task.status === 'completed'));
  const threads = f.state.nodes.map(node => node.threads.codex);
  assert.ok(threads.every(Boolean)); assert.equal(new Set(threads).size, 6);
  assert.ok(f.state.tasks.every(task => task.threadId === f.state.nodes.find(node => node.id === task.nodeId)!.threads.codex));
  assert.ok(f.clients.every(client => client.options.cwd === f.root));
  const sessions = f.clients.flatMap(client => client.calls.filter(call => call.method === 'thread/start' || call.method === 'thread/resume'));
  assert.equal(sessions.filter(call => call.method === 'thread/start').length, 6);
  assert.ok(sessions.every(call => call.params.cwd === f.root));
  assert.ok(sessions.some(call => call.method === 'thread/resume' && call.params.threadId === frontend.threadId));

  const saved = f.store.read()!;
  await f.engine.close();
  const restored = new WorkflowEngine({ workbenchRoot: f.root, executable: 'unused', nativeFactory() { assert.fail('reading durable workflow must not start native execution'); } });
  t.after(() => restored.close()); await restored.init();
  const snapshot = (await restored.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  assert.equal(snapshot.project.template, 'web-product');
  assert.deepEqual(snapshot.nodes.map(node => node.threadId), threads);
  assert.deepEqual(snapshot.messages!.map(message => message.message_id), saved.messages.map(message => message.message_id));
  assert.deepEqual(snapshot.tasks.find(task => task.id === acceptance.id)!.result, acceptanceResult);
  assert.deepEqual(snapshot.conversation!.find(entry => entry.id === rawOutput.id)!.rawItem, qaOutput);
  assert.equal(readFileSync(resolveMessageArtifact(f.root, saved, requirementArtifact.artifact_id), 'utf8'), requirementsText);
});
