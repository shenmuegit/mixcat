  await f.invoke('design', 'request_review', { request_id: 'definition-ui', checkpoint_id: 'ui-ue', title: 'Corrected static design', content: { originalTestMessage: passed.message_id, issueId }, attachments: [{ path: paths[1] }, { path: paths[2] }], item_ids: documentRefs.slice(1).map(reference => reference.id) }, 'definition-ui');
  const ui = f.state.humanReviews[1];
  const definition = { iteration: 'mvp-001', requirement: 'REQ-1', originalTestMessage: passed.message_id, issueId, reviewIds: [direction.id, ui.id], limitations: ['static design only'] };
  const summary = await send('design', 'product', 'definition-summary', definition, { attachments: artifacts.map(artifact => ({ artifact_id: artifact.artifact_id })) });
  f.finish(reviewedDesign);
  const aggregate = await running(summary.target_task_id);
  assert.equal(aggregate.threadId, product.threadId);
  const handoff = await send('product', 'architect', 'definition-handoff', definition, { attachments: artifacts.map(artifact => ({ artifact_id: artifact.artifact_id })), work_context: work });
  const handoffSource = f.context('product', 'definition-handoff-replay', aggregate);
  assert.equal(handoff.accepted, true);
  const waiting = f.state.tasks.find(task => task.id === handoff.target_task_id)!;
  assert.equal(waiting.status, 'waiting_review'); assert.equal(waiting.turnId, null);
  assert.deepEqual(waiting.reviewDependencies!.map(dependency => dependency.reviewId), [direction.id, ui.id]);
  f.finish(aggregate);
  await decide(ui, 'definition-ui-approved');
  const designNotice = await running(f.state.humanReviews.find(review => review.id === ui.id)!.decision!.continuationTaskId!);
  const architect = await running(handoff.target_task_id);
  const architectureContext = await f.invoke('architect', 'get_project_context', {}, 'definition-architecture-context');
  assert.deepEqual(architectureContext.task.input, definition);
  assert.equal(architectureContext.work_context.primary_todo_id, todo.id);
  assert.ok(architectureContext.work_context.observed.some((item: { id: string }) => item.id === issueId));
  assert.ok(architectureContext.work_context.observed.every((item: object) => !Object.hasOwn(item, 'body')));
  assert.deepEqual(architectureContext.incoming_message.attachments.map((artifact: { artifact_id: string }) => readFileSync(resolveMessageArtifact(f.root, f.state, artifact.artifact_id), 'utf8')), [requirementsText, uiText, reportText]);
  const feedback = await send('architect', 'product', 'definition-feasibility', { question: 'Should offline retry be in scope?' }, { reply_to: handoff.message_id });
  f.finish(architect); f.finish(designNotice);
  const productFeedback = await running(feedback.target_task_id);
  assert.equal(productFeedback.threadId, product.threadId);
  const nextRound = await send('product', 'requirements', 'definition-next-round', { question: 'Clarify offline retry scope', previousHandoff: handoff.message_id, architectureFeedback: feedback.message_id });
  f.finish(productFeedback);
  const nextRequirements = await running(nextRound.target_task_id);
  assert.equal(nextRequirements.threadId, requirements.threadId); f.finish(nextRequirements);
  writeFileSync(join(f.root, paths[1]), 'UI v3: later work must not rewrite the old handoff.\n');
  writeFileSync(join(f.root, paths[2]), 'Later report.\n');
  await f.engine.command({ type: 'search_project_items', projectId: f.projectId, query: { kind: 'document' } });
  const handoffEdge = f.state.edges.find(edge => edge.id === 'product-architect')!;
  const replay = await f.invoke('product', edgeToolName(handoffEdge.id, 'architect'), { request_id: 'definition-handoff', content: definition, reason: handoffEdge.condition, attachments: artifacts.map(artifact => ({ artifact_id: artifact.artifact_id })), work_context: work }, 'definition-handoff-replay', handoffSource);
  assert.deepEqual(replay, handoff, 'accepted handoff replay keeps its original material observations and receipt');
  const staleInput = await f.engine.command({ type: 'send_message', projectId: f.projectId, nodeId: 'architect', mode: 'codex', input: [{ type: 'text', text: 'Continue with the changed design' }], work_context: work });
  const staleTask = staleInput.snapshot.selected!.tasks.at(-1)!;
  assert.equal(staleTask.status, 'waiting_review'); assert.equal(staleTask.turnId, null);
  const snapshot = (await f.engine.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  assert.equal(snapshot.humanReviews![1].materialsCurrent, false);
  assert.deepEqual(snapshot.humanReviews!.map(review => review.decision!.commandId), ['definition-direction-approved', 'definition-ui-approved']);
  const saved = f.store.read()!;
  await f.engine.close();
  const restored = new WorkflowEngine({ workbenchRoot: f.root, executable: 'unused', nativeFactory() { assert.fail('completed product definition must reopen without running a model'); } });
  t.after(() => restored.close()); await restored.init();
  const reopened = (await restored.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  assert.deepEqual(reopened.groups, snapshot.groups);
  assert.deepEqual(reopened.humanReviews!.map(review => review.bundleHash), snapshot.humanReviews!.map(review => review.bundleHash));
  assert.deepEqual(reopened.tasks.find(task => task.id === handoff.target_task_id)!.workContext, waiting.workContext);
  assert.equal(reopened.tasks.find(task => task.id === staleTask.id)!.status, 'waiting_review');
  assert.deepEqual(artifacts.map(artifact => readFileSync(resolveMessageArtifact(f.root, saved, artifact.artifact_id), 'utf8')), [requirementsText, uiText, reportText]);
