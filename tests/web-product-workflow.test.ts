  const decide = (review: HumanReviewView, actionId: string) => f.engine.command({ type: 'decide_review', projectId: f.projectId, reviewId: review.id, version: review.version, bundleHash: review.bundleHash, decision: 'approved', comment: 'CONTROLLED FIXTURE human decision' }, actionId);
  const requirementsText = 'REQ-1: preserve input and keep it available after an error.\n';
  const uiText = 'UI v2: submit, loading, exact response, retain text and retry after error.\n';
  const reportText = 'Independent static design check: error-state defect fixed; prototype/backend behavior unverified.\n';
  writeFileSync(join(f.root, 'docs/design/requirements.md'), requirementsText);
  writeFileSync(join(f.root, 'docs/design/ui-ux.md'), 'UI v1: submit, loading and exact response; no error state.\n');
  const todo = (await f.engine.command({ type: 'update_project_item', projectId: f.projectId, input: { request_id: 'definition-work', operation: 'create', kind: 'todo', title: 'Define exact response behavior', ownerId: 'product' } })).projectItem!.item;
  const documents = (await f.engine.command({ type: 'search_project_items', projectId: f.projectId, query: { kind: 'document' } })).projectItems!.items;
  const paths = ['docs/design/requirements.md', 'docs/design/ui-ux.md', 'docs/reports/mvp-001/ui-ue-test-report.md'];
  const documentRefs = paths.map(path => ({ projectId: f.projectId, kind: 'document' as const, id: documents.find(item => item.path === path)!.id }));
  const work: WorkContext = { primary_todo_id: todo.id, references: documentRefs };
  await f.engine.command({ type: 'send_message', projectId: f.projectId, nodeId: 'product', mode: 'codex', input: [{ type: 'text', text: 'Define and test the design before architecture' }], work_context: work });
  const product = await running(f.state.tasks[0].id);
  const brief = await send('product', 'requirements', 'definition-brief', { scope: 'REQ-1' });
  const requirements = await running(brief.target_task_id);
  const designRequest = await send('requirements', 'design', 'definition-design', { requirement: 'REQ-1' }, { attachments: [{ path: paths[0] }] });
  assert.equal(f.state.tasks.find(task => task.id === designRequest.target_task_id)!.status, 'waiting_review');
  f.finish(requirements);
  await f.invoke('product', 'request_review', { request_id: 'definition-direction', checkpoint_id: 'product-direction', title: 'Exact response direction', content: { requirement: 'REQ-1' }, attachments: [{ path: 'docs/design/product-brief.md' }, { path: paths[0] }] }, 'definition-direction');
  const direction = f.state.humanReviews[0];
  f.finish(product);
  await decide(direction, 'definition-direction-approved');
  const directionNotice = await running(f.state.humanReviews.find(review => review.id === direction.id)!.decision!.continuationTaskId!);
  assert.equal(directionNotice.threadId, product.threadId); f.finish(directionNotice);
  const design = await running(designRequest.target_task_id);
  const gap = await send('design', 'requirements', 'definition-gap', { question: 'Which rule covers failed submit?' }, { reply_to: designRequest.message_id });
  f.finish(design);
  const clarification = await running(gap.target_task_id);
  assert.equal(clarification.threadId, requirements.threadId);
  const rule = await send('requirements', 'design', 'definition-rule', { answer: 'REQ-1 explicitly retains input after error' }, { reply_to: gap.message_id });
  f.finish(clarification);
  const clarifiedDesign = await running(rule.target_task_id);
  const check = await send('design', 'design-test', 'definition-check', { scope: 'static design', requirement: 'REQ-1' }, { attachments: [{ path: paths[0] }, { path: paths[1] }] });
  f.finish(clarifiedDesign);
  const tester = await running(check.target_task_id);
  assert.equal(tester.reviewDependencies!.length, 1, 'design testing must not wait for the UI/UE review it helps produce');
  const issueResult = await f.invoke('design-test', 'update_project_item', { request_id: 'definition-defect', operation: 'create', kind: 'issue', issueType: 'bug', title: 'Missing retained input after error', body: 'Location: submit error. Expected: preserve text for retry. Actual: no error state.' }, 'definition-defect');
  const issueId = issueResult.receipt.itemId as string;
  work.references.push({ projectId: f.projectId, kind: 'issue', id: issueId });
  const defect = await send('design-test', 'design', 'definition-defect-return', { issueId, location: 'submit error', basis: 'REQ-1', impact: 'cannot retry', scope: 'static design' }, { reply_to: check.message_id, work_context: work });
  f.finish(tester);
  const correction = await running(defect.target_task_id);
  assert.equal(correction.threadId, design.threadId);
  writeFileSync(join(f.root, paths[1]), uiText);
  const recheck = await send('design', 'design-test', 'definition-recheck', { issueId, changed: 'error state' }, { reply_to: defect.message_id, attachments: [{ path: paths[1] }] });
