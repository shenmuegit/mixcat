test('a node asks without a checkpoint and receives the exact answer once in its original paused thread', async t => {
  const f = await reviewFixture(t), source = await f.active('plan');
  const input = { request_id: 'delivery-format', title: '交付形式', content: '需要可运行的 .exe，还是浏览器网页？' };
  const receipt = await f.invoke('plan', 'request_review', input, 'ask');
  assert.deepEqual(await f.invoke('plan', 'request_review', input, 'ask-again'), receipt);
  const review = f.state.humanReviews[0];
  assert.equal(review.kind, 'question');
  assert.equal(review.content, input.content);
  assert.equal(review.nodeId, 'plan');
  assert.equal(review.threadId, source.threadId);
  assert.equal(f.state.reviewPolicy.checkpoints.length, 0);
  await f.send('plan'); f.finish(source);
  const waiting = f.state.tasks.find(task => task.nodeId === 'plan' && task.id !== source.id)!;
  assert.equal(waiting.status, 'waiting_review');
  assert.equal(f.state.nodes.find(node => node.id === 'plan')!.status, 'blocked');
  await f.active('implement');
  await f.engine.command({ type: 'pause_node', projectId: f.projectId, nodeId: 'plan' });
  const turns = f.turns().length, answer = '  .exe\n只需要加减法  ';
  const command = { type: 'decide_review' as const, projectId: f.projectId, reviewId: review.id, version: review.version, bundleHash: review.bundleHash, decision: 'approved' as const, comment: answer };
  await f.engine.command(command, 'answer-delivery');
  await f.engine.command(command, 'answer-delivery');
  const answered = f.state.humanReviews[0];
  assert.equal(answered.decision?.comment, answer);
  assert.equal(f.turns().length, turns, 'Answering must not enable a paused node');
  const continuation = f.state.tasks.filter(task => task.id === answered.decision?.continuationTaskId);
  assert.equal(continuation.length, 1);
  assert.equal(continuation[0].threadId, source.threadId);
  assert.match(continuation[0].instruction, /用户回答/);
  assert(continuation[0].instruction.includes(answer));
  assert.equal(f.store.read()!.humanReviews[0].decision!.comment, answer);
  const snapshot = (await f.engine.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  assert.equal(snapshot.humanReviews![0].kind, 'question');
  assert.equal(snapshot.humanReviews![0].status, 'approved');
  assert.equal(waiting.status, 'queued');
  await f.engine.command({ type: 'resume_node', projectId: f.projectId, nodeId: 'plan' });
  await until(() => !!waiting.turnId);
  f.finish(waiting);
  await until(() => !!continuation[0].turnId);
  const delivered = f.turns().find(call => call.params.input.some((item: any) => typeof item.text === 'string' && item.text.includes(answer)));
  assert(delivered);
  assert.equal(delivered.params.threadId, source.threadId);
});

test('pending standalone questions survive engine restart without creating a native session or an answer', async t => {
  const f = await reviewFixture(t), source = await f.active('plan');
  await f.invoke('plan', 'request_review', { request_id: 'restart', title: '待回答', content: '保留这个问题' }, 'restart');
  f.finish(source);
  await f.engine.close();
  const restored = new WorkflowEngine({ workbenchRoot: f.root, executable: 'fixture', accountFactory: accountFixture().factory, nativeFactory() { throw new Error('Restart must not dispatch without an answer'); } });
  t.after(() => restored.close());
  await restored.init();
  const snapshot = (await restored.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  assert.equal(snapshot.humanReviews!.length, 1);
  assert.equal(snapshot.humanReviews![0].kind, 'question');
  assert.equal(snapshot.humanReviews![0].status, 'pending');
  assert.equal(snapshot.humanReviews![0].content, '保留这个问题');
  assert.equal(snapshot.humanReviews![0].decision, null);
  assert.equal(snapshot.tasks.length, 1);
  assert.equal(snapshot.nodes.find(node => node.id === 'plan')!.status, 'blocked');
});

test('native questions keep the original request until the exact response is sent successfully', async t => {
  const f = await reviewFixture(t), source = await f.active('plan'), sent: { id: unknown; result: unknown }[] = [];
  let fail = true;
  f.clients[0].port.respond = (id, result) => { if (fail) throw new Error('Native reply write failed'); sent.push({ id, result }); };
  f.clients[0].options.onRequest!({ id: 'native-question', method: 'item/tool/requestUserInput', params: { threadId: source.threadId, turnId: source.turnId, questions: [{ id: 'format', question: '交付形式？', options: null, isSecret: false, isOther: true, header: '形式' }] } });
  const snapshot = (await f.engine.command({ type: 'snapshot', projectId: f.projectId })).snapshot.selected!;
  const request = snapshot.requests![0];
  assert.equal(request.nodeId, 'plan');
  const result = { answers: { format: { answers: ['  .exe  '] } } };
  const command = { type: 'respond_native' as const, projectId: f.projectId, requestKey: request.key, result };
  await assert.rejects(f.engine.command(command), /Native reply write failed/);
  assert.equal((await f.engine.command({ type: 'snapshot' })).snapshot.selected!.requests!.length, 1);
  fail = false;
  await f.engine.command(command);
  assert.deepEqual(sent, [{ id: 'native-question', result }]);
  assert.equal((await f.engine.command({ type: 'snapshot' })).snapshot.selected!.requests!.length, 0);
  await assert.rejects(f.engine.command(command));
  assert.equal(sent.length, 1);
});

test('question and answer storage failures leave no partial question, approval or continuation', async t => {
  const f = await reviewFixture(t); await f.active('plan');
  const save = f.store.save.bind(f.store);
  f.store.save = () => { throw new Error('Fixture disk write failed'); };
  const input = { request_id: 'storage', title: '确认', content: '可以继续吗？' };
  await assert.rejects(f.invoke('plan', 'request_review', input, 'save-fail'), /STORAGE_UNAVAILABLE|disk write/);
  assert.equal(f.state.humanReviews.length, 0);
  f.store.save = save;
  await f.invoke('plan', 'request_review', input, 'save-retry');
  const question = f.state.humanReviews[0], before = f.state.tasks.length;
  f.store.save = () => { throw new Error('Fixture disk write failed'); };
  const command = { type: 'decide_review' as const, projectId: f.projectId, reviewId: question.id, version: question.version, bundleHash: question.bundleHash, decision: 'approved' as const, comment: '继续' };
  await assert.rejects(f.engine.command(command, 'answer-storage'), /disk write/);
  assert.equal(f.state.humanReviews[0].status, 'pending');
  assert.equal(f.state.humanReviews[0].decision, null);
  assert.equal(f.state.tasks.length, before);
  f.store.save = save;
  await f.engine.command(command, 'answer-storage');
  assert.equal(f.state.humanReviews[0].decision!.comment, '继续');
  assert.equal(f.state.tasks.length, before + 1);
});

test('independent questions preserve identity, capability and legacy checkpoint validation', async t => {
  const f = await reviewFixture(t); await f.active('plan'); await f.active('implement');
  const ask = { request_id: 'question-one', title: '选择', content: { question: '继续吗？' } };
  await f.invoke('plan', 'request_review', ask, 'ask-one');
  await f.invoke('implement', 'request_review', { ...ask, request_id: 'question-two' }, 'ask-two');
  assert.equal(f.state.humanReviews.length, 2);
  assert.notEqual(f.state.humanReviews[0].checkpointId, f.state.humanReviews[1].checkpointId);
  await assert.rejects(f.invoke('plan', 'request_review', { ...ask, content: 'changed' }, 'conflict'), /REQUEST_CONFLICT|不同核对/);
  await assert.rejects(f.invoke('plan', 'request_review', { ...ask, request_id: 'invalid', checkpoint_id: 'missing' }, 'invalid'), /责任节点|核对点/);
  const first = f.state.humanReviews[0];
  await assert.rejects(f.engine.command({ type: 'decide_review', projectId: f.projectId, reviewId: first.id, version: first.version, bundleHash: first.bundleHash, decision: 'approved', comment: '' }, 'empty'), /回答/);
  assert.equal(first.status, 'pending');
  await f.engine.command({ type: 'pause_node', projectId: f.projectId, nodeId: 'plan' });
  await assert.rejects(f.invoke('plan', 'request_review', { ...ask, request_id: 'paused' }, 'paused'), /SOURCE_NOT_ACTIVE|暂停/);
  assert.equal(f.state.humanReviews.length, 2);
  await until(() => f.state.humanReviews[1].status === 'pending');
});
